"""Held-out daily stability and descriptive peak patterns, using actual aggregates."""

import json
from datetime import datetime
from pathlib import Path
import numpy as np
import pandas as pd
from raahi.config import PROCESSED, REPORTS, ROOT
from raahi.model import dense_history

f = pd.read_parquet(PROCESSED / "route_daily.parquet")
f["date"] = pd.to_datetime(f["date"]).dt.strftime("%Y-%m-%d")
validation = json.loads((REPORTS / "validation.json").read_text())
minutes = validation["selected_minutes"]
v = next(v for v in validation["variants"] if v["minutes"] == minutes)
dates = v["train_dates"] + v["validation_dates"]
split = len(v["train_dates"])
types = np.array([int(datetime.fromisoformat(d).weekday() >= 5) for d in dates])
daily = {
    d: {"absolute_error": 0.0, "actual_passengers": 0.0, "cells": 0}
    for d in dates[split:]
}
for _, frame in f.groupby("route_key"):
    y = dense_history(frame, dates, minutes)[:, :, 0]
    train = y[:split]
    mean_slot = train.mean(axis=0)
    for i in range(split, len(dates)):
        comparable = train[types[:split] == types[i]]
        prediction = np.where(
            np.count_nonzero(comparable, axis=0) >= 3,
            (comparable.sum(axis=0) + 3 * mean_slot) / (len(comparable) + 3),
            mean_slot,
        )
        d = daily[dates[i]]
        d["absolute_error"] += float(np.abs(y[i] - prediction).sum())
        d["actual_passengers"] += float(y[i].sum())
        d["cells"] += y.shape[1]
for d in daily.values():
    d["mae"] = round(d["absolute_error"] / d["cells"], 4)
    d["wape"] = (
        round(d["absolute_error"] / d["actual_passengers"], 4)
        if d["actual_passengers"]
        else None
    )
q = json.loads((REPORTS / "data-quality.json").read_text())
weekday = [
    dict(
        weekday=r["weekday"],
        observed_days=r["days"],
        mean_daily_sampled_passengers=round(r["passengers"] / r["days"], 2),
    )
    for r in q["weekdays"]
]
peaks = sorted(q["hourly"], key=lambda r: r["passengers"], reverse=True)[:5]
result = dict(
    daily_validation=daily,
    weekday_means=weekday,
    largest_observed_hours=peaks,
    interpretation="Transaction-demand patterns only. Commute-like peaks are an internal plausibility check, not independent occupancy ground truth.",
)
(REPORTS / "pattern-checks.json").write_text(
    json.dumps(result, indent=2), encoding="utf-8"
)
doc = "# Historical pattern checks\n\nGenerated by `python scripts/check_patterns.py`.\n\n## Held-out daily stability\n\n| Date | MAE | WAPE |\n|---|---:|---:|\n"
for date, d in daily.items():
    doc += f"| {date} | {d['mae']} | {d['wape']:.2%} |\n"
doc += (
    "\n## Weekday averages (normalised by observed days)\n\n```json\n"
    + json.dumps(weekday, indent=2)
    + "\n```\n\n## Largest transaction hours\n\n```json\n"
    + json.dumps(peaks, indent=2)
    + "\n```\n\n"
    + result["interpretation"]
    + "\n"
)
(ROOT / "docs/model/pattern-checks.md").write_text(doc, encoding="utf-8")
print(json.dumps(result, indent=2))
