/**
 * Returns localized stop name, appending Devanagari transliteration if in Hindi mode.
 */
export function getStopDisplayName(stopName: string, lang: Language): string {
  if (lang === "hi") {
    const hindi = stopHindiMap[stopName.trim()];
    if (hindi) return `${hindi} (${stopName})`;
  }
  return stopName;
}
